export function getProduct(sku: string) {
  return PRODUCTS.find((p) => p.sku === sku);
}

export function searchProducts(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return PRODUCTS;
  return PRODUCTS.filter((p) => {
    const hay = [p.name, p.sku, p.origin, p.notesForAgents, ...p.aliases, p.category]
      .join(" ")
      .toLowerCase();
    return hay.includes(q);
  });
}

export function catalogForAgents() {
  return PRODUCTS.map((p) => ({
    sku: p.sku,
    name: p.name,
    aliases: p.aliases,
    category: p.category,
    unit: p.unit,
    pack_qty: p.packQty,
    pack_unit: p.packUnit,
    price_inr: p.pricePaise / 100,
    mrp_inr: p.mrpPaise / 100,
    currency: "INR",
    stock: p.stock,
    gst_pct: p.gstPct,
    origin: p.origin,
    notes: p.notesForAgents,
    substitutions: p.substitutions,
    perishable: p.perishable,
  }));
}
